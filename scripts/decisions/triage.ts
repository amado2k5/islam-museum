#!/usr/bin/env tsx
/**
 * triage — judge-assisted digest of unlabelled safe-default holds.
 *
 * For every live record held at safe-default with NO founder verdict yet,
 * re-runs the question through decide() and then maybeJudge() (requires
 * DECIDE_JUDGE_URL or DECIDE_JUDGE_CMD — see `npm run decisions:local`),
 * producing a markdown table the founder can scan: engine hold vs the local
 * model's bidirectional recommendation, dissent flag, confidence.
 *
 * Advisory only — nothing here writes records or changes engine outcomes.
 *
 * Usage:
 *   DECIDE_JUDGE_URL=http://localhost:11434/v1/chat/completions \
 *   DECIDE_JUDGE_MODEL=qwen2.5:32b \
 *   npx tsx scripts/decisions/triage.ts [--write docs/decisions/triage.md]
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";
import { decide, loadPrecedents, maybeJudge } from "./decide";

const DIR = join(process.cwd(), "docs/decisions/records");
const WRITE = process.argv.includes("--write");
const OUT = process.argv[process.argv.indexOf("--write") + 1] ?? join(process.cwd(), "docs/decisions/triage.md");

interface Rec {
  id?: string; status?: string; step?: string; question?: string;
  supersedes?: string; domain?: string;
  calibration_log?: { founder_resolution?: { verdict?: string } | null };
}

const recs: Rec[] = [];
for (const f of readdirSync(DIR).filter((f) => f.endsWith(".yaml")).sort()) {
  try { recs.push(parse(readFileSync(join(DIR, f), "utf8")) as Rec); }
  catch { /* skip */ }
}
const superseded = new Set(recs.map((r) => r.supersedes).filter((x): x is string => !!x));
const targets = recs.filter((r) =>
  r.status === "decided" && r.step === "safe-default" && r.question
  && !superseded.has(r.id ?? "")
  && !r.calibration_log?.founder_resolution?.verdict);

if (!process.env.DECIDE_JUDGE_URL && !process.env.DECIDE_JUDGE_CMD) {
  console.error("no judge configured — set DECIDE_JUDGE_URL/DECIDE_JUDGE_CMD (see npm run decisions:local)");
  process.exit(2);
}

const corpus = loadPrecedents();
const rows: { id: string; q: string; domain: string; outcome: string; rec: string; conf: string; dissent: boolean }[] = [];
for (const [i, r] of targets.entries()) {
  const q = { question: r.question! };
  const d = decide(q, corpus, "conservative");
  const j = await maybeJudge(q, d);
  const outcome = j.status === "recommended" ? "recommended" : j.judge_dissent ? "dissent" : "hold";
  const rec = String(j.decision ?? "").replace(/\s+/g, " ").slice(0, 140);
  const conf = j.calibration_log && typeof j.calibration_log === "object"
    ? String((j.calibration_log as Record<string, unknown>).framing_entropy ?? "—") : "—";
  rows.push({ id: r.id ?? "?", q: r.question!, domain: r.domain ?? "?", outcome, rec, conf, dissent: !!j.judge_dissent });
  console.log(`[${i + 1}/${targets.length}] ${r.id} → ${outcome}`);
}

const model = process.env.DECIDE_JUDGE_MODEL ?? process.env.DECIDE_JUDGE_CMD ?? "judge";
const lines = [
  "# Decision triage — judge recommendations on unlabelled holds",
  "",
  `Generated by scripts/decisions/triage.ts with ${model}. Advisory only — the engine's safe-default stands; these are inputs to the founder's async verdicts.`,
  "",
  `| record | domain | judge outcome | uncertainty | recommendation (truncated) |`,
  `|---|---|---|---|---|`,
  ...rows.map((r) => `| ${r.id} | ${r.domain} | ${r.outcome}${r.dissent ? " ⚠" : ""} | ${r.conf} | ${r.rec.replace(/\|/g, "\\|")} |`),
  "",
];
const md = lines.join("\n");
if (WRITE) { writeFileSync(OUT, md); console.log(`wrote ${OUT}`); }
else console.log("\n" + md);
