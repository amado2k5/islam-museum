// Prose completion: how many entities in the prose classes have full, partial
// or empty prose in each language. Measured the same way as the enrichment
// queue (scripts/enrichment-queue.ts), so the numbers agree with its gaps.
//
//   npx tsx scripts/prose-completion.ts          print the counts
//   npx tsx scripts/prose-completion.ts --write  also rewrite
//                                                docs/library/enrichment/prose-completion.md
//                                                (one history row per day)
//
// full     the file exists and is not partial
// partial  the file exists and has fewer than 500 body characters, or fewer
//          than two headings and fewer than 1,500 characters
// empty    there is no file for that language

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const LANGS = ["ar", "en", "ur"] as const;
const PROSE_CLASSES = ["award", "building", "concept", "course", "event", "exhibit", "group", "invention", "job", "journey", "language", "listing", "object", "period", "person", "place", "polity", "practice", "question", "screen", "work"];
const PARTIAL = { minChars: 500, minCharsOneSection: 1500 };
const DOC = "docs/library/enrichment/prose-completion.md";

function walk(dir: string, ext: string): string[] {
  if (!existsSync(dir)) return [];
  const out: string[] = [];
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) out.push(...walk(p, ext));
    else if (n.endsWith(ext)) out.push(p);
  }
  return out;
}

function isPartial(file: string): boolean {
  const raw = readFileSync(file, "utf8");
  const fm = raw.startsWith("---") ? raw.indexOf("\n---", 3) : -1;
  let body = fm > 0 ? raw.slice(fm + 4) : raw;
  const heads = (body.match(/^#{2,3} /gm) || []).length;
  body = body
    .replace(/^#+ .*$/gm, "")
    .replace(/\{cite:[^}]*\}/g, "")
    .replace(/\[\[[^|\]]*\|?([^\]]*)\]\]/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
  const chars = [...body].length;
  return chars < PARTIAL.minChars || (heads < 2 && chars < PARTIAL.minCharsOneSection);
}

function measure() {
  const ents: { cls: string; slug: string }[] = [];
  for (const cls of PROSE_CLASSES)
    for (const f of walk(join("data", cls), ".yaml")) {
      const name = f.split("/").pop() ?? "";
      if (!name.startsWith("_")) ents.push({ cls, slug: name.replace(/\.yaml$/, "") });
    }
  const total = ents.length;
  const counts: Record<string, { full: number; partial: number; empty: number }> = {};
  for (const l of LANGS) {
    let full = 0, partial = 0, empty = 0;
    for (const e of ents) {
      const f = join("content", l, e.cls, `${e.slug}.md`);
      if (!existsSync(f)) empty++;
      else if (isPartial(f)) partial++;
      else full++;
    }
    counts[l] = { full, partial, empty };
  }
  return { total, counts };
}

const pct = (n: number, t: number) => `${((100 * n) / t).toFixed(1)}%`;

function render(today: string, total: number, counts: Record<string, { full: number; partial: number; empty: number }>, history: string[]): string {
  const row = (l: string) => {
    const c = counts[l];
    return `| ${l} | ${c.full.toLocaleString("en-US")} (${pct(c.full, total)}) | ${c.partial.toLocaleString("en-US")} (${pct(c.partial, total)}) | ${c.empty.toLocaleString("en-US")} (${pct(c.empty, total)}) |`;
  };
  return `# Prose completion

Generated by \`npx tsx scripts/prose-completion.ts --write\`. Do not edit the table by hand; the history is kept by the script.

**Goal (founder rule, 14 November 2026):** every entity in the prose classes has full prose in Arabic, English and Urdu. Until then, the share of **full** prose rises and the shares of **partial** and **empty** fall. This number is checked at least once a day, and the history below is the record of it.

## Latest measurement (${today})

Base: ${total.toLocaleString("en-US")} entities in the prose classes (every \`data/<class>/\` file except those whose name starts with \`_\`).

| Language | Full | Partial | Empty |
|---|---|---|---|
${LANGS.map(row).join("\n")}

**Definitions.** *Full*: the prose file exists and is not partial. *Partial*: the file exists and has fewer than 500 body characters, or fewer than two headings and fewer than 1,500 characters (body text counted without frontmatter, headings and citation tokens). *Empty*: there is no file for that language. The same rule drives the \`prose.missing\` and \`prose.partial\` gaps in the enrichment queue.

## Where the work is

Work the empty and partial prose first, highest score first:

\`\`\`
npm run enrichment-queue -- --gap prose.missing.ar --class place --limit 25
npm run enrichment-queue -- --gap prose.partial.en --limit 40
\`\`\`

Claim each item in \`claims.yaml\` before you write it.

## Daily update

Run the script once a day on \`main\`, commit the regenerated file with a canary entry, and let the lander or a docs pull request carry it. If the day's run is skipped, the next run records the gap; do not back-fill rows.

## History

| Date | Entities | Arabic full / partial / empty | English full / partial / empty | Urdu full / partial / empty |
|---|---|---|---|---|
${history.join("\n")}
`;
}

function main() {
  const write = process.argv.includes("--write");
  const { total, counts } = measure();
  const today = new Date().toLocaleDateString("en-CA"); // YYYY-MM-DD in local time
  const cell = (l: string) => {
    const c = counts[l];
    return `${c.full.toLocaleString("en-US")} / ${c.partial.toLocaleString("en-US")} / ${c.empty.toLocaleString("en-US")}`;
  };
  const newRow = `| ${today} | ${total.toLocaleString("en-US")} | ${cell("ar")} | ${cell("en")} | ${cell("ur")} |`;
  console.log(`entities in prose classes: ${total}`);
  for (const l of LANGS) {
    const c = counts[l];
    console.log(`${l}: full ${c.full} (${pct(c.full, total)}), partial ${c.partial} (${pct(c.partial, total)}), empty ${c.empty} (${pct(c.empty, total)})`);
  }
  if (!write) return;
  let history: string[] = [];
  if (existsSync(DOC)) {
    history = readFileSync(DOC, "utf8").split("\n").filter((l) => /^\| \d{4}-\d{2}-\d{2} \|/.test(l));
  }
  history = history.filter((l) => !l.startsWith(`| ${today} |`));
  history.push(newRow);
  writeFileSync(DOC, render(today, total, counts, history));
  console.log(`wrote ${DOC}`);
}

main();
