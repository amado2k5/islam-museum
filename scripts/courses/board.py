#!/usr/bin/env python3
"""The board of docs/courses-mission/VERIFICATION.md, written from the oracles' own captured last lines. Nothing is typed.

  python3 scripts/courses/board.py            # rewrite the board from docs/courses-mission/oracle-output/*.out
  python3 scripts/courses/board.py --check    # fail if the board in the ledger differs from what the outputs say

It does not run the oracles (some take ten minutes, one needs the network): run each with --save first; the "How to
re-run" table in the ledger lists the commands. The board names, for every row, the commit its oracle ran at.
"""
import os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "docs", "courses-mission", "oracle-output")
ROWS = [
    ("1", "The audit is measured: tree, schema and surface inventoried from the repository and the live site", "o01-audit-before", "scripts/courses/o01_audit.py", "python3 scripts/courses/o01_audit.py --at 800467e93e --save"),
    ("2, 3", "The prototype serves every lesson in Arabic and English; every lesson is at most three interactions from the courses home", "o03-taps", "scripts/courses/o03_taps.mjs", "node scripts/courses/o03_taps.mjs --save"),
    ("4, 5", "Every connection's entity is a real record with a source; enrichment cites only what the museum already cited", "o04-mapping", "scripts/courses/o04_mapping.py", "python3 scripts/courses/o04_mapping.py --save"),
    ("6", "Curriculum fidelity of the proof course: code for code, text for text, against the authority's document", "../../courses/gates/check-ca-on-g4-social-studies", "scripts/courses/check_course.py", "python3 scripts/courses/check_course.py course/ca-on-g4-social-studies --official .cache/curricula/ontario-sshg-2023-g4/official.json --strict --save"),
    ("7", "The proof course was ingested by a fresh-context agent using only PIPELINE.md", "o07-proof-run", "scripts/courses/o07_proof_run.py", "python3 scripts/courses/o07_proof_run.py --save"),
    ("8", "Ship gates at the branch head: validate prints `0 errors`; cite-check prints `0 fail`", "o08-gates", "scripts/courses/o08_gates.py", "python3 scripts/courses/o08_gates.py --save"),
    ("9", "The vision pass: committed screenshots, three widths, two languages, every defect confirmed gone or registered", "o09-vision", "scripts/courses/o09_vision.py", "python3 scripts/courses/defects.py && python3 scripts/courses/o09_vision.py --save"),
    ("10", "With JavaScript disabled every lesson is reachable and readable", "o10-nojs", "scripts/courses/o10_nojs.mjs", "node scripts/courses/o10_nojs.mjs --save"),
    ("11", "Boundaries held: Urdu untouched, the rest of the site renders as before, no account or tracking", "o11-boundaries", "scripts/courses/o11_boundaries.py", "python3 scripts/courses/o11_boundaries.py --save"),
    ("12", "The baseline is frozen and concurrency is accounted for", "o12-baseline", "scripts/courses/o12_baseline.py", "python3 scripts/courses/o12_baseline.py --save"),
]


def board():
    lines = ["| Statement | State | The oracle's own last line | Ran at commit | Oracle (a committed file) | Command | Captured output |", "|---|---|---|---|---|---|---|"]
    green = 0
    for num, title, slug, script, cmd in ROWS:
        f = os.path.join(OUT, slug + ".out")
        if not os.path.exists(f):
            lines.append(f"| **{num}** {title} | **NOT RUN** | no captured output | | `{script}` | `{cmd}` | |")
            continue
        t = open(f, encoding="utf-8").read().strip().splitlines()
        last = t[-1].replace("RESULT: ", "")
        m = re.search(r"run at commit ([0-9a-f]{10})", "\n".join(t[:3]))
        state = "GREEN" if last.startswith("GREEN") else "NOT-GREEN"
        green += state == "GREEN"
        lines.append(f"| **{num}** {title} | **{state}** | {last.replace('|', '/')} | `{m.group(1) if m else '?'}` | `{script}` | `{cmd}` | `docs/courses-mission/oracle-output/{slug}.out` |")
    lines += ["", f"{green} of {len(ROWS)} oracle runs end GREEN."]
    return "\n".join(lines)


def main():
    p = os.path.join(ROOT, "docs", "courses-mission", "VERIFICATION.md")
    t = open(p, encoding="utf-8").read()
    a, b = "<!-- BOARD:BEGIN (generated by scripts/courses/board.py; do not edit by hand) -->", "<!-- BOARD:END -->"
    new = t[: t.index(a) + len(a)] + "\n\n" + board() + "\n\n" + t[t.index(b):]
    if "--check" in sys.argv:
        print("board matches the captured outputs" if new == t else "BOARD IS STALE: run python3 scripts/courses/board.py")
        sys.exit(0 if new == t else 1)
    open(p, "w", encoding="utf-8").write(new)
    print(board().splitlines()[-1])


if __name__ == "__main__":
    main()
