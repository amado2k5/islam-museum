#!/usr/bin/env python3
"""The state of every course on the branch, counted from the files themselves (not from any agent's report).

  python3 scripts/courses/fleet_report.py            # prints the table
  python3 scripts/courses/fleet_report.py --write    # also writes docs/courses/FLEET.md

For each subject: lessons, connections, distinct records linked, specific expectations in lessons, entries in its gap
register, the last line of its saved ingestion gate, and whether a run log and an evidence table exist.
A course that ended "gap only" has a gap register and a run log and no records; it is listed too.
"""
import glob, os, sys, yaml
from lib import ROOT, courses, tree, baseline_has

cs = courses()
rows = []
subjects = sorted(i for i, d in cs.items() if d["kind"] == "subject")
seen = set()
for sid in subjects:
    slug = sid.split("/")[1]
    seen.add(slug)
    ids = tree(cs, sid)
    lessons = [i for i in ids if cs[i]["kind"] == "lesson"]
    conns = [c for i in lessons for c in cs[i].get("connections", [])]
    codes = {e["code"] for i in lessons for e in cs[i].get("expectations", [])}
    gp = os.path.join(ROOT, "docs", "courses", "gaps", slug + ".yaml")
    gaps = len((yaml.safe_load(open(gp, encoding="utf-8")) or {}).get("gaps", [])) if os.path.exists(gp) else None
    gate = os.path.join(ROOT, "docs", "courses", "gates", f"check-{slug}.out")
    last = open(gate, encoding="utf-8").read().strip().splitlines()[-1].replace("RESULT: ", "") if os.path.exists(gate) else "no saved gate"
    grade = next((cs[p].get("grade_number") for p in [cs[sid].get("part_of")] if p in cs), "")
    rows.append((grade or 0, slug, (cs[sid].get("label") or {}).get("en", ""), "pilot" if baseline_has(f"data/{sid}.yaml") else "pipeline", len(lessons), len(conns), len({c.get("entity") for c in conns if c.get("entity")}), len(codes), gaps, last,
                 os.path.exists(os.path.join(ROOT, "docs", "courses", "runs", slug + ".md")), os.path.exists(os.path.join(ROOT, "docs", "courses", "evidence", slug + ".md"))))
for gp in sorted(glob.glob(os.path.join(ROOT, "docs", "courses", "gaps", "*.yaml"))):
    slug = os.path.basename(gp)[:-5]
    if slug not in seen:
        gaps = len((yaml.safe_load(open(gp, encoding="utf-8")) or {}).get("gaps", []))
        rows.append((0, slug, "(gap only: no record)", "pipeline", 0, 0, 0, 0, gaps, "gap only", os.path.exists(os.path.join(ROOT, "docs", "courses", "runs", slug + ".md")), False))
rows.sort()
out = ["| Grade | Course | Made by | Lessons | Connections | Records linked | Expectations in lessons | In the gap register | Ingestion gate | Run log | Evidence |", "|---|---|---|---|---|---|---|---|---|---|---|"]
for g, slug, label, by, nl, nc, nr, ne, ng, last, log, ev in rows:
    out.append(f"| {g or ''} | `{slug}` {label} | {by} | {nl} | {nc} | {nr} | {ne} | {'' if ng is None else ng} | {last} | {'yes' if log else 'no'} | {'yes' if ev else 'no'} |")
tot = lambda k: sum(r[k] for r in rows)
green = sum(1 for r in rows if str(r[9]).startswith("GREEN"))
summary = f"{len(rows)} courses; {tot(4)} lessons; {tot(5)} connections; {tot(7)} expectations in lessons; {sum(r[8] or 0 for r in rows)} in gap registers; ingestion gate GREEN for {green}."
print("\n".join(out))
print()
print(summary)
if "--write" in sys.argv:
    open(os.path.join(ROOT, "docs", "courses", "FLEET.md"), "w", encoding="utf-8").write("# Every course on the branch, counted from the files\n\nGenerated by `python3 scripts/courses/fleet_report.py --write`. Do not edit by hand. The counts are read from the records, the gap registers and the saved gate outputs, not from any agent's report.\n\n" + "\n".join(out) + "\n\n" + summary + "\n")
