// Modern Islam Browser census: how many existing records fall in the browser's window and in which derived section.
// Run: npm run modern:census  -> docs/modern-islam/coverage.md (never hand-edited). Counts are measured, not estimated.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadEntities, p } from "../lib.js";
import { inWindow, SECTION_IDS, sectionsOf, taxonomy, type RecordLike } from "./sections.js";

export interface Census {
  inWindow: number;
  bySection: Record<string, number>;
  bySectionClass: Record<string, Record<string, number>>;
  unsectioned: Record<string, number>;
  awards: number;
  withHonours: number;
  withFootprint: number;
  withReach: number;
  withHorizon: number;
}

export function buildCensus(records: RecordLike[]): Census {
  const awardsById = new Map(records.filter((r) => r.class === "award").map((r) => [r.id as string, r]));
  const bySection: Record<string, number> = Object.fromEntries(SECTION_IDS.map((s) => [s, 0]));
  const bySectionClass: Record<string, Record<string, number>> = Object.fromEntries(SECTION_IDS.map((s) => [s, {}]));
  const unsectioned: Record<string, number> = {};
  let windowed = 0;
  for (const r of records) {
    if (!inWindow(r)) continue;
    windowed++;
    const sections = sectionsOf(r, awardsById);
    if (!sections.length) { unsectioned[r.class] = (unsectioned[r.class] ?? 0) + 1; continue; }
    for (const s of sections) {
      bySection[s] = (bySection[s] ?? 0) + 1;
      bySectionClass[s][r.class] = (bySectionClass[s][r.class] ?? 0) + 1;
    }
  }
  return {
    inWindow: windowed,
    bySection,
    bySectionClass,
    unsectioned: Object.fromEntries(Object.entries(unsectioned).sort(([a], [b]) => a.localeCompare(b))),
    awards: awardsById.size,
    withHonours: records.filter((r) => (r.honours ?? []).length).length,
    withFootprint: records.filter((r) => r.footprint).length,
    withReach: records.filter((r) => (r.reach ?? []).length).length,
    withHorizon: records.filter((r) => r.horizon).length,
  };
}

export function renderCensus(c: Census): string {
  const row = (s: string) => {
    const classes = Object.entries(c.bySectionClass[s] ?? {}).sort(([, a], [, b]) => b - a).map(([k, n]) => `${k} ${n}`).join(", ");
    return `| ${s} | ${taxonomy.sections.find((x) => x.id === s)?.label.en ?? s} | ${c.bySection[s] ?? 0} | ${classes || "—"} |`;
  };
  const unsectioned = Object.entries(c.unsectioned).map(([k, n]) => `${k} ${n}`).join(", ") || "none";
  return [
    "# Modern Islam Browser coverage",
    "",
    "_Generated by `npm run modern:census` from the records in `data/`; a record's section is derived (scripts/modern/sections.ts), never typed._",
    "",
    `Records with a dated fact in the window (1976 onward) or a horizon: **${c.inWindow}** · award records: **${c.awards}** · records with honours: **${c.withHonours}** · with a footprint block: **${c.withFootprint}** · with dated reach figures: **${c.withReach}** · with a horizon: **${c.withHorizon}**.`,
    "",
    "## Records per derived section",
    "",
    "| Section | Label | Records | By class |",
    "|---|---|---:|---|",
    ...SECTION_IDS.map(row),
    "",
    `In the window but in no section (a class or kind the browser does not show, such as a lecture or a Made-wing shop): ${unsectioned}.`,
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const records = loadEntities().map(({ entity }) => entity as RecordLike);
  const census = buildCensus(records);
  const out = p("docs", "modern-islam", "coverage.md");
  writeFileSync(out, renderCensus(census));
  console.log(`modern census: ${census.inWindow} records in the window across ${SECTION_IDS.length} sections -> docs/modern-islam/coverage.md`);
}
