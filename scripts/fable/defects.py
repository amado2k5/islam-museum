#!/usr/bin/env python3
"""Builds the defect register of the vision pass (statement 8) from the reviewers' own tables.

Reads every docs/fable-run/vision/review-*.md, takes each table row whose first cell is a defect id (a letter and a
number), and joins it with docs/fable-run/vision/decisions.json (what was done about it). Writes
docs/fable-run/vision/defects.json. A defect with no decision is written with status "undecided", which the oracle
(o08_vision.py) refuses.

  python3 scripts/fable/defects.py
"""
import collections, glob, json, os, re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
V = os.path.join(ROOT, "docs/fable-run/vision")
dec = json.load(open(os.path.join(V, "decisions.json"), encoding="utf-8"))
out, seen = [], set()
for path in sorted(glob.glob(os.path.join(V, "review-*.md"))):
    for line in open(path, encoding="utf-8"):
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 5 or not re.fullmatch(r"[A-Z]\d{1,3}", cells[0]) or cells[0] in seen:
            continue
        if cells[1] in ("GONE", "STILL THERE", "CHANGED") or cells[1].split(" ")[0] in ("GONE", "STILL", "CHANGED"):
            continue  # a re-check row of an earlier defect, not a new defect
        seen.add(cells[0])
        d = dec["ids"].get(cells[0]) or dec["defaults"].get(cells[0][0]) or {"status": "undecided", "where": "?", "note": ""}
        out.append({"id": cells[0], "review": os.path.basename(path), "severity": cells[-1].lower(), "screenshots": cells[1], "place": cells[2], "description": " | ".join(cells[3:-1]), "status": d["status"], "where": d["where"], "note": d["note"]})
out.sort(key=lambda d: (d["id"][0], int(d["id"][1:])))
json.dump({"note": "Generated by scripts/fable/defects.py from the reviewers' tables and decisions.json. Do not hand-edit.", "defects": out}, open(os.path.join(V, "defects.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
c = collections.Counter((d["where"], d["status"]) for d in out)
print(f"{len(out)} defects: " + "; ".join(f"{w}/{s}: {n}" for (w, s), n in sorted(c.items())))
print("by severity:", dict(collections.Counter(d["severity"] for d in out)))
und = [d["id"] for d in out if d["status"] == "undecided"]
if und:
    print("UNDECIDED:", ", ".join(und))
