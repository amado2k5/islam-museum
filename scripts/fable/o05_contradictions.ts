// Statement 5: the cross-record contradiction sweep is complete; every contradiction is fixed or registered; none is left silently.
//
//   npx tsx scripts/fable/o05_contradictions.ts                      check: detect on the current graph, compare with the register
//   npx tsx scripts/fable/o05_contradictions.ts --init <graph.json>  create the register from a detection run (once, at the baseline)
//   npx tsx scripts/fable/o05_contradictions.ts --merge <file.json>  apply adjudications [{key, status, resolution}] to the register
//   npx tsx scripts/fable/o05_contradictions.ts --write-md           rewrite docs/fable-run/CONTRADICTIONS.md from the register
//
// The register (docs/fable-run/contradictions/register.json) holds one entry per finding ever detected, with its evidence and
// a status: `registered` (stands, with its evidence and the reason it was not fixed), `fixed` (corrected from already-cited
// sources; the detector no longer fires) or `not-a-contradiction` (read and found consistent; the reason is recorded).
// Green means: every finding the detectors raise today is in the register and not marked fixed; every entry marked fixed
// is no longer raised; every entry carries evidence; every adjudicated entry carries its reason.
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { p } from "../lib.js";
import { detect, type Finding } from "./contradictions.js";

type Status = "registered" | "fixed" | "not-a-contradiction";
interface Entry extends Finding { status: Status; resolution: string }
interface Register { detected_at_commit: string | null; note: string; entries: Entry[] }
const FILE = p("docs", "fable-run", "contradictions", "register.json");
const sh = (c: string) => execSync(c, { cwd: p(), encoding: "utf8" }).trim();
const load = (): Register => JSON.parse(readFileSync(FILE, "utf8"));
const save = (r: Register) => writeFileSync(FILE, JSON.stringify(r, null, 1) + "\n");
const args = process.argv.slice(2);

if (args[0] === "--init") {
  if (existsSync(FILE)) { console.error("the register already exists; it is never re-created"); process.exit(2); }
  const { commit, findings } = detect(args[1]);
  save({ detected_at_commit: commit, note: "One entry per cross-record contradiction the detectors in scripts/fable/contradictions.ts raised. Entries are never deleted; a later detection run may add entries.", entries: findings.map((f) => ({ ...f, status: "registered", resolution: "" })) });
  console.log(`register created from graph commit ${commit}: ${findings.length} entries`);
  process.exit(0);
}
if (args[0] === "--merge") {
  const reg = load();
  const byKey = new Map(reg.entries.map((e) => [e.key, e]));
  let n = 0;
  for (const a of JSON.parse(readFileSync(args[1], "utf8")) as { key: string; status: Status; resolution: string }[]) {
    const e = byKey.get(a.key);
    if (!e) { console.error(`unknown key: ${a.key}`); process.exit(2); }
    if (!["registered", "fixed", "not-a-contradiction"].includes(a.status) || !a.resolution?.trim()) { console.error(`bad adjudication for ${a.key}`); process.exit(2); }
    e.status = a.status; e.resolution = a.resolution.trim(); n++;
  }
  save(reg);
  console.log(`merged ${n} adjudications`);
  process.exit(0);
}

const reg = load();
if (args[0] === "--write-md") {
  const count = (s: Status) => reg.entries.filter((e) => e.status === s).length;
  const L = ["# Cross-record contradictions: the register", "",
    "_Generated by `npx tsx scripts/fable/o05_contradictions.ts --write-md` from `docs/fable-run/contradictions/register.json`. Do not hand-edit._", "",
    "A contradiction here is two records, or two fields, that cannot both be right as written. The detectors and their exact rules are in `scripts/fable/contradictions.ts`. This register holds every finding they raised, whatever became of it.", "",
    `| Found | Fixed from already-cited sources | Stand registered with their evidence | Read and found consistent |`, "|---|---|---|---|",
    `| ${reg.entries.length} | ${count("fixed")} | ${count("registered")} | ${count("not-a-contradiction")} |`, "",
    `First detection: graph built from commit \`${reg.detected_at_commit}\`.`, ""];
  const kinds = [...new Set(reg.entries.map((e) => `${e.detector} ${e.kind}`))].sort();
  for (const k of kinds) {
    const es = reg.entries.filter((e) => `${e.detector} ${e.kind}` === k);
    L.push(`## ${k.slice(2)} (${es.length})`, "", "| Status | Records | Evidence | What was done, or why it stands |", "|---|---|---|---|");
    for (const e of es) L.push(`| ${e.status} | ${e.records.map((r) => "`" + r + "`").join(" · ")} | ${e.evidence.replace(/\|/g, "\\|").replace(/\n/g, " ")} | ${(e.resolution || "Not yet read by an adjudicator. It stands on the evidence in this row.").replace(/\|/g, "\\|").replace(/\n/g, " ")} |`);
    L.push("");
  }
  writeFileSync(p("docs", "fable-run", "CONTRADICTIONS.md"), L.join("\n"));
  console.log("wrote docs/fable-run/CONTRADICTIONS.md");
  process.exit(0);
}

// ---- the oracle ----
const graph = JSON.parse(readFileSync(p(".cache", "graph.json"), "utf8").slice(0, 400).replace(/,"nodes".*/s, "}"));
const head = sh("git rev-parse HEAD");
const dirty = sh("git status --porcelain -- data content tour schema scripts site i18n").split("\n").filter(Boolean).length;
console.log("ORACLE 05: the cross-record contradiction sweep is complete; nothing is left silently (statement 5)");
console.log("file: scripts/fable/o05_contradictions.ts (detectors: scripts/fable/contradictions.ts)");
console.log(`HEAD: ${head}`);
console.log(`uncommitted paths under data/ content/ tour/ schema/ scripts/ site/ i18n/: ${dirty}${dirty ? "  (the numbers below describe the working tree, not HEAD)" : ""}`);
const { commit, findings } = detect();
console.log(`graph artifact: .cache/graph.json; built from commit ${commit}`);
console.log("-".repeat(78));
let ok = true; const failed: string[] = [];
const check = (name: string, pass: boolean, detail = "") => { if (!pass) { ok = false; failed.push(name); } console.log(`[${pass ? "PASS" : "FAIL"}] ${name}${detail ? ": " + detail : ""}`); };
if (commit !== head) { ok = false; failed.push("graph artifact is stale"); console.log("WARNING: the graph artifact was built from a different commit than HEAD. Run `npm run graph` and re-run."); }
const byKey = new Map(reg.entries.map((e) => [e.key, e]));
const now = new Set(findings.map((f) => f.key));
const count = (s: Status) => reg.entries.filter((e) => e.status === s).length;
console.log(`register: ${reg.entries.length} entries (first detection at graph commit ${reg.detected_at_commit})`);
console.log(`  fixed from already-cited sources:        ${count("fixed")}`);
console.log(`  stand registered with their evidence:    ${count("registered")}`);
console.log(`  read and found consistent:               ${count("not-a-contradiction")}`);
console.log(`detectors raise today: ${findings.length}`);
const byKind: Record<string, [number, number]> = {};
for (const e of reg.entries) { const k = `${e.detector} ${e.kind}`; byKind[k] ??= [0, 0]; byKind[k][0]++; if (now.has(e.key)) byKind[k][1]++; }
for (const [k, [a, b]] of Object.entries(byKind).sort()) console.log(`  ${String(a).padStart(4)} found, ${String(b).padStart(4)} still raised  ${k}`);
const silent = findings.filter((f) => !byKey.has(f.key));
check("every contradiction the detectors raise today is in the register", silent.length === 0, silent.length ? `${silent.length} not registered: ${silent.slice(0, 5).map((f) => f.key).join("; ")}` : `${findings.length} raised, all registered`);
const notFixed = reg.entries.filter((e) => e.status === "fixed" && now.has(e.key));
check("every entry marked fixed is no longer raised", notFixed.length === 0, notFixed.slice(0, 5).map((e) => e.key).join("; "));
const gone = reg.entries.filter((e) => e.status !== "fixed" && !now.has(e.key));
check("no entry vanished without being marked fixed (a finding that stops firing must be accounted for)", gone.length === 0, gone.slice(0, 5).map((e) => e.key).join("; "));
check("every entry carries its evidence", reg.entries.every((e) => e.evidence?.trim()));
const noReason = reg.entries.filter((e) => e.status !== "registered" && !e.resolution.trim());
check("every fixed or dismissed entry records what was done or why", noReason.length === 0, `${noReason.length} without a reason`);
const unread = reg.entries.filter((e) => e.status === "registered" && !e.resolution.trim()).length;
console.log(`  entries registered on the detector's evidence alone, not yet read by an adjudicator: ${unread}`);
console.log("-".repeat(78));
console.log(ok ? "RESULT: GREEN (5 checks passed)" : `RESULT: NOT-GREEN (${failed.length} failed: ${failed.join("; ")})`);
process.exit(ok ? 0 : 1);
