#!/usr/bin/env python3
"""Writes docs/gaming/traceability.md from the corrective plan and the two gate files, so the three cannot disagree,
and with it the production plan, the inventory of the target images and the historical-review ledger, each from its own file.

Usage, from the repository root or from gaming/:  python3 gaming/tools/traceability.py [--check]
With --check it writes nothing and fails if the page on disk is not what it would write.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs" / "gaming"
plan = json.loads((DOCS / "spec-corrective" / "plan.json").read_text())
platform = json.loads((DOCS / "acceptance.json").read_text())["requirements"]
granada = json.loads((DOCS / "granada" / "acceptance.json").read_text())["gates"]
gates = {g["id"]: g for g in platform + granada}

items = plan["items"]
known = set(plan["statusValues"])
for item in items:
    if item["status"] not in known:
        sys.exit(f"item {item['id']}: unknown status {item['status']!r}")
    for gate in item["gates"]:
        if gate not in gates:
            sys.exit(f"item {item['id']} names a gate that does not exist: {gate}")
covering = {gid: [i for i in items if gid in i["gates"]] for gid in gates}

def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")

out = []
out.append("# The gaming platform: every gate and every piece of corrective work, in one table")
out.append("")
out.append("_Generated by `npm --prefix gaming run traceability` from [`spec-corrective/plan.json`](spec-corrective/plan.json), [`acceptance.json`](acceptance.json) and [`granada/acceptance.json`](granada/acceptance.json). Do not edit it by hand: change those files and run the command. What the corrective mandate is, and how it is used, is in [`spec-corrective/README.md`](spec-corrective/README.md)._")
out.append("")
b = plan["baseline"]
out.append(f"**Checked {plan['checked']}.** The mandate's baseline: {b['mandateBaseline']}. On UAT when checked: {b['uatWhenChecked']}. On `main` when checked: {b['mainWhenChecked']}. Machine: {b['machine']}. Evidence of the baseline: [`{b['evidence'].split('docs/gaming/')[1]}`]({b['evidence'].split('docs/gaming/')[1]}).")
out.append("")
count = {}
for g in gates.values():
    count[g["status"]] = count.get(g["status"], 0) + 1
out.append(f"**The gates today:** {len(gates)} in all; " + ", ".join(f"{n} {s}" for s, n in sorted(count.items())) + ". No gate is passed on a screenshot, on a test of code alone, or on the author's own opinion of the picture or the play.")
out.append("")
out.append("## The corrective work")
out.append("")
out.append("| # | Work | Priority | Where it stands | Checked against the repository | Moved since the mandate's baseline | Next action | The founder's to decide |")
out.append("|---:|---|---|---|---|---|---|---|")
for i in items:
    out.append(f"| {i['id']} | **{cell(i['title'])}** ({', '.join(i['gates']) or 'no gate of its own'}) | {i['priority']}, {i['size']} | {i['status']} | {cell(i['checked'])} | {cell(i['movedSince'])} | {cell(i['next'])} | {cell(i['founder'] or 'nothing')} |")
out.append("")
waiting = [i for i in items if i["founder"]]
out.append("## What waits on the founder")
out.append("")
for i in waiting:
    out.append(f"- **{i['id']}. {i['title']}:** {i['founder']}")
out.append("")
handoff = plan.get("handoff")
if handoff:
    out.append("## The production handoff's twelve prompts")
    out.append("")
    out.append(f"_From {handoff['source']}, received {handoff['received']}. Each belongs to pieces of the corrective work above._")
    out.append("")
    out.append("| Prompt | What it asks for | Priority | Belongs to | Where it stands |")
    out.append("|---:|---|---|---|---|")
    for q in handoff["prompts"]:
        if q["status"] not in known:
            sys.exit(f"prompt {q['id']}: unknown status {q['status']!r}")
        out.append(f"| {q['id']} | **{cell(q['title'])}** | {q['priority']} | {', '.join(str(n) for n in q['belongsTo'])} | {q['status']}: {cell(q['standing'])} |")
    out.append("")
    if handoff.get("decisions"):
        answered = handoff["answered"]
        out.append(f"## The founder's decisions of {answered['on']}")
        out.append("")
        out.append(f"_His answer to the reviewer's questions and to three points the developer raised, kept as it arrived in [`{answered['record'].split('/')[-1]}`](spec-production/{answered['record'].split('/')[-1]}). These are summaries; his words govern._")
        out.append("")
        out.append("| | On | Decided | Where it is taken up |")
        out.append("|---|---|---|---|")
        for x in handoff["decisions"]:
            out.append(f"| {x['id']} | **{cell(x['on'])}** | {cell(x['decided'])} | {cell(x['where'])} |")
        out.append("")
        out.append("## Decisions that still need the founder")
        out.append("")
        for x in handoff["openDecisions"]:
            out.append(f"- **{x['id']}.** {x['needs']}" + (f" _{x['note']}_" if x["note"] else ""))
        out.append("")
matrix_file = DOCS / "regression" / "matrix.json"
if matrix_file.exists():
    matrix = json.loads(matrix_file.read_text())
    rows = matrix["scenarios"]
    for r in rows:
        if r["covered"] not in ("yes", "partly", "no"):
            sys.exit(f"scenario {r['id']}: unknown cover {r['covered']!r}")
        for h in r["how"]:
            if h not in matrix["how"]:
                sys.exit(f"scenario {r['id']}: unknown way {h!r}")
    tally = {c: sum(1 for r in rows if r["covered"] == c) for c in ("yes", "partly", "no")}
    on_host = sum(1 for r in rows if "host" in r["how"])
    out.append("## The regression scenarios, run on every release")
    out.append("")
    out.append(f"_From {matrix['source']}, as mapped in [`regression/matrix.json`](regression/matrix.json). Of {len(rows)} scenarios, {tally['yes']} are covered, {tally['partly']} partly and {tally['no']} not at all; {on_host} are played on the deployed host itself. A script shows that a thing still works, never that a game is good._")
    out.append("")
    out.append("**How each is run:** " + "; ".join(f"`{k}`: {v}" for k, v in matrix["how"].items()) + ".")
    out.append("")
    out.append("| Scenario | Game | What it asks | Covered | How | By | Not covered |")
    out.append("|---|---|---|---|---|---|---|")
    for r in rows:
        out.append(f"| {r['id']} | {r['game']} | {cell(r['asks'])} | {r['covered']} | {', '.join(r['how'])} | {cell(r['by'])} | {cell(r['missing'])} |")
    out.append("")
out.append("## Every gate")
out.append("")
out.append("| Gate | What it asks | Status | Corrective work that bears on it | What exists as evidence |")
out.append("|---|---|---|---|---|")
for gid, g in gates.items():
    work = ", ".join(f"{i['id']} ({i['status']})" for i in covering[gid]) or "none named by the mandate"
    evidence = g.get("evidenceSoFar", "")
    if len(evidence) > 260:
        evidence = evidence[:257].rsplit(" ", 1)[0] + " …"
    out.append(f"| {gid} | {cell(g['requirement'])} | **{g['status']}** | {work} | {cell(evidence)} |")
out.append("")
pages = {DOCS / "traceability.md": "\n".join(out)}

# ---- The production plan, the inventory of the target images and the historical-review ledger: each a page made from
# its own file, so the page and the file cannot disagree.
PROD = DOCS / "spec-production"
plan_file, inventory_file, ledger_file = PROD / "production-plan.json", PROD / "target-inventory.json", DOCS / "historical-review" / "ledger.json"
if plan_file.exists() and inventory_file.exists():
    pp = json.loads(plan_file.read_text())
    inv = json.loads(inventory_file.read_text())
    packs = {x["id"]: x for x in pp["packages"]}
    for x in pp["packages"]:
        if x["stream"] not in pp["streams"]:
            sys.exit(f"package {x['id']}: unknown stream")
        for dep in x["dependsOn"]:
            if dep not in packs:
                sys.exit(f"package {x['id']} depends on {dep}, which does not exist")

    def sessions(x):
        lo, hi = x["sessions"]
        return "people, not sessions" if hi == 0 else (str(lo) if lo == hi else f"{lo} to {hi}")

    o = ["# The production plan: phases, streams, dependencies, estimates and gates", ""]
    o.append(f"_Generated by `npm --prefix gaming run traceability` from [`production-plan.json`](production-plan.json); edit that file, not this page. Written {pp['written']} on the founder's instruction of that day ([`owner-decisions-2026-11-26.md`](owner-decisions-2026-11-26.md)). **It is a plan. Nothing in it is done unless [`../LEDGER.md`](../LEDGER.md) says so, and all three games are prototypes.**_")
    o.append("")
    o.append(f"**What an estimate here is.** {pp['session']} {pp['basis']}")
    o.append("")
    o.append("## The phases")
    o.append("")
    o.append("| Phase | What it is | Where it stands | Packages | Estimate, in sessions |")
    o.append("|---:|---|---|---|---|")
    for ph in pp["phases"]:
        mine = [x for x in pp["packages"] if x["phase"] == ph["id"]]
        lo, hi = sum(x["sessions"][0] for x in mine), sum(x["sessions"][1] for x in mine)
        o.append(f"| {ph['id']} | **{cell(ph['title'])}.** {cell(ph['what'])} | {cell(ph['state'])} | {', '.join(x['id'] for x in mine) or 'none'} | {f'{lo} to {hi}' if hi else 'none'} |")
    lo, hi = sum(x["sessions"][0] for x in pp["packages"]), sum(x["sessions"][1] for x in pp["packages"])
    o.append("")
    o.append(f"**In all:** {len(pp['packages'])} packages, {lo} to {hi} sessions by the estimates below, not counting anything that waits on people.")
    o.append("")
    for key, name in pp["streams"].items():
        mine = [x for x in pp["packages"] if x["stream"] == key]
        lo, hi = sum(x["sessions"][0] for x in mine), sum(x["sessions"][1] for x in mine)
        o.append(f"## {name} ({lo} to {hi} sessions)")
        o.append("")
        o.append("| | Work | Phase | Depends on | Estimate | It is done when | It waits on |")
        o.append("|---|---|---:|---|---|---|---|")
        for x in mine:
            o.append(f"| {x['id']} | {cell(x['title'])} | {x['phase']} | {', '.join(x['dependsOn']) or 'nothing'} | {sessions(x)} | {cell(x['gate'])} | {cell(x['waitsOn'])} |")
        o.append("")
    pages[PROD / "production-plan.md"] = "\n".join(o)

    o = ["# The three target images: every system they show, and how each is to be met", ""]
    o.append("_Generated by `npm --prefix gaming run traceability` from [`target-inventory.json`](target-inventory.json); edit that file, not this page._")
    o.append("")
    o.append(f"**The rule.** {inv['rule']}")
    o.append("")
    everything = [i for gm in inv["games"] for i in gm["items"]]
    o.append(f"**Today:** {len(everything)} systems are listed; " + ", ".join(f"{sum(1 for i in everything if i['today'] == v)} {v}" for v in inv["todayValues"]) + ". " + "; ".join(f"{sum(1 for i in everything if i['disposition'] == k)} {v}" for k, v in inv["dispositions"].items()) + ". The list is the developer's reading of each image; a system the founder sees that is not here is added, not argued.")
    o.append("")
    for gm in inv["games"]:
        image = "../" + gm["image"].split("docs/gaming/")[1]
        o.append(f"## {gm['game']}")
        o.append("")
        o.append(f"The target: [`{gm['image'].split('/')[-1]}`]({image}). " + ", ".join(f"{sum(1 for i in gm['items'] if i['today'] == v)} {v}" for v in inv["todayValues"]) + ".")
        o.append("")
        o.append("| | Where | The image shows | It must | Today | How it is met | Work | Needs |")
        o.append("|---|---|---|---|---|---|---|---|")
        for i in gm["items"]:
            if i["today"] not in inv["todayValues"] or i["disposition"] not in inv["dispositions"]:
                sys.exit(f"{i['id']}: unknown value")
            for w in i["work"]:
                if w and w not in packs:
                    sys.exit(f"{i['id']} names package {w}, which does not exist")
            o.append(f"| {i['id']} | {cell(i['where'])} | {cell(i['shows'])} | {cell(i['mustDo'])} | **{i['today']}**{': ' + cell(i['todayNote']) if i['todayNote'] else ''} | {i['disposition']} | {', '.join(w for w in i['work'] if w)} | {cell(i['needs'])} |")
        o.append("")
    pages[PROD / "target-inventory.md"] = "\n".join(o)
if ledger_file.exists():
    led = json.loads(ledger_file.read_text())
    o = ["# The historical-review ledger: every statement of history the games make", ""]
    o.append("_Generated by `npm --prefix gaming run traceability` from [`ledger.json`](ledger.json); edit that file, not this page. How it is used: [`README.md`](README.md)._")
    o.append("")
    o.append(f"**The rule.** {led['rule']}")
    o.append("")
    tally = {k: sum(1 for e in led["entries"] if e["decision"] == k) for k in led["decisions"]}
    o.append(f"**Today:** {len(led['entries'])} entries; " + ", ".join(f"{n} {k}" for k, n in tally.items() if n) + ". Reviewers named: " + (", ".join(led["reviewers"]) or "none") + ". Editor: " + (led["editor"] or "none") + ".")
    o.append("")
    o.append("**Kinds:** " + "; ".join(f"`{k}`: {v}" for k, v in led["kinds"].items()) + ".")
    o.append("")
    o.append("| | Game | The claim | Where in the game | Source | Kind | Uncertainty | Reviewer | Decision | Approved |")
    o.append("|---|---|---|---|---|---|---|---|---|---|")
    for e in led["entries"]:
        if e["decision"] not in led["decisions"] or e["kind"] not in led["kinds"]:
            sys.exit(f"{e['id']}: unknown value")
        if e["decision"] != "pending" and not (e["reviewer"] and e["approved"]):
            sys.exit(f"{e['id']}: a decision needs a named reviewer and a date")
        src = ", ".join(f"`{x}`" if "/" in x and " " not in x else x for x in e["sources"]) or "none"
        o.append(f"| {e['id']} | {e['game']} | {cell(e['claim'])} | {cell(e['context'])} | {cell(src)} | {e['kind']} | {cell(e['uncertainty'])}{' ' + cell(e['note']) if e['note'] else ''} | {e['reviewer'] or 'none named'} | {e['decision']} | {e['approved'] or ''} |")
    o.append("")
    pages[DOCS / "historical-review" / "ledger.md"] = "\n".join(o)

if "--check" in sys.argv:
    for page, text in pages.items():
        if not page.exists() or page.read_text() != text:
            sys.exit(f"{page.relative_to(ROOT)} is stale: run `npm --prefix gaming run traceability`")
    print("; ".join(str(page.relative_to(ROOT)) for page in pages) + ": current")
else:
    for page, text in pages.items():
        page.write_text(text)
    print(f"wrote {', '.join(page.name for page in pages)}: {len(items)} pieces of work, {len(gates)} gates")
