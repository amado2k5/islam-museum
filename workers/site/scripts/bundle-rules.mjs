// Bundles the site's _redirects and _headers files into the Worker as a module.
//
// Static assets on Workers consume these two files themselves and do not serve
// them, so env.ASSETS.fetch("/_redirects") answers 404 inside the Worker. The
// Worker needs the rules for the HTML paths it serves from R2, so this script
// copies the files into src/rules.generated.js before every deploy.
//
// Usage: node workers/site/scripts/bundle-rules.mjs [public-dir] [out-file]
// Defaults: site/public (the source of both files) and workers/site/src/rules.generated.js.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../../..");

export function bundleRules(publicDir = join(repoRoot, "site/public"), outFile = join(here, "../src/rules.generated.js")) {
  const read = (name) => {
    const path = join(publicDir, name);
    if (!existsSync(path)) throw new Error(`missing ${path}: the site's ${name} file is required`);
    return readFileSync(path, "utf8");
  };
  const redirects = read("_redirects");
  const headers = read("_headers");
  const source =
    "// Generated by workers/site/scripts/bundle-rules.mjs from site/public. Do not edit; not committed.\n" +
    `export const redirectsText = ${JSON.stringify(redirects)};\n` +
    `export const headersText = ${JSON.stringify(headers)};\n`;
  writeFileSync(outFile, source);
  return { outFile, redirects, headers };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [publicDir, outFile] = process.argv.slice(2);
  const result = bundleRules(publicDir ? resolve(publicDir) : undefined, outFile ? resolve(outFile) : undefined);
  console.log(`[bundle-rules] wrote ${result.outFile} (${result.redirects.split("\n").length} redirect lines, ${result.headers.split("\n").length} header lines)`);
}
