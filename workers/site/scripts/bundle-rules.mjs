// Bundles the site's _redirects and _headers files into the Worker as a module.
//
// Static assets on Workers consume these two files themselves and do not serve
// them, so env.ASSETS.fetch("/_redirects") answers 404 inside the Worker. The
// Worker needs the rules for the HTML paths it serves from R2, so this script
// copies the files into src/rules.generated.js before every deploy.
//
// Usage: node workers/site/scripts/bundle-rules.mjs [public-dir] [out-file]
// Defaults: site/public (the source of both files) and workers/site/src/rules.generated.js.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../../..");

// Every entity's aliases (its former ids after a rename or a merge) -> its current id.
// AGENTS.md: ids are immutable and renames go through aliases; the Worker turns each
// alias into a 301 to the current id in every language, so a cited URL never breaks.
// Both YAML forms are read without a parser: "aliases: [a/b, c/d]" and a block of
// "- a/b" lines (indented or not) under "aliases:".
export function scanAliases(dataDir = join(repoRoot, "data")) {
  const aliases = {};
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const full = join(dir, name);
      if (statSync(full).isDirectory()) { if (!name.startsWith("_")) walk(full); continue; }
      if (!name.endsWith(".yaml") || name.startsWith("_")) continue;
      const id = `${dir.slice(dataDir.length + 1).split("/")[0]}/${name.slice(0, -5)}`;
      const text = readFileSync(full, "utf8");
      const m = text.match(/^aliases:[ \t]*(.*)$/m);
      if (!m) continue;
      let ids = [];
      const inline = m[1].trim();
      if (inline.startsWith("[")) {
        ids = inline.slice(1, inline.lastIndexOf("]")).split(",").map((x) => x.trim().replace(/^["']|["']$/g, "")).filter(Boolean);
      } else if (inline === "" || inline.startsWith("#")) {
        const rest = text.slice(m.index + m[0].length);
        for (const line of rest.split("\n").slice(1)) {
          const item = line.match(/^[ \t]*-[ \t]*["']?([a-z]+\/[^"'\s#]+)["']?/);
          if (item) ids.push(item[1]);
          else if (line.trim() !== "" && !line.trim().startsWith("#")) break;
        }
      }
      for (const a of ids) if (/^[a-z]+\/[A-Za-z0-9._-]+$/.test(a) && a !== id) aliases[a] = id;
    }
  };
  walk(dataDir);
  return aliases;
}

export function bundleRules(publicDir = join(repoRoot, "site/public"), outFile = join(here, "../src/rules.generated.js"), dataDir = join(repoRoot, "data")) {
  const read = (name) => {
    const path = join(publicDir, name);
    if (!existsSync(path)) throw new Error(`missing ${path}: the site's ${name} file is required`);
    return readFileSync(path, "utf8");
  };
  const redirects = read("_redirects");
  const headers = read("_headers");
  const aliases = existsSync(dataDir) ? scanAliases(dataDir) : {};
  const source =
    "// Generated by workers/site/scripts/bundle-rules.mjs from site/public and data/. Do not edit; not committed.\n" +
    `export const redirectsText = ${JSON.stringify(redirects)};\n` +
    `export const headersText = ${JSON.stringify(headers)};\n` +
    `export const aliasesText = ${JSON.stringify(JSON.stringify(aliases))};\n`;
  writeFileSync(outFile, source);
  return { outFile, redirects, headers, aliases };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [publicDir, outFile] = process.argv.slice(2);
  const result = bundleRules(publicDir ? resolve(publicDir) : undefined, outFile ? resolve(outFile) : undefined);
  console.log(`[bundle-rules] wrote ${result.outFile} (${result.redirects.split("\n").length} redirect lines, ${result.headers.split("\n").length} header lines, ${Object.keys(result.aliases).length} entity aliases)`);
}
