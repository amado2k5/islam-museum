// Run: node --test workers/site/test/
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { bundleRules } from "../scripts/bundle-rules.mjs";
import { parseRedirects, parseDynamicRedirects, parseHeaders, headersFor } from "../src/route.js";

test("bundleRules writes a module whose text parses into the same rules", async () => {
  const dir = mkdtempSync(join(tmpdir(), "bundle-rules-"));
  const publicDir = join(dir, "public");
  mkdirSync(publicDir);
  writeFileSync(join(publicDir, "_redirects"), "/api/* https://api.example/api/:splat 301\n/ar/old/ /ar/new/ 301\n");
  writeFileSync(join(publicDir, "_headers"), "/\n  Link: </x>; rel=\"y\"\n");
  const out = join(dir, "rules.generated.js");
  bundleRules(publicDir, out);
  const mod = await import(`file://${out}`);
  assert.equal(parseRedirects(mod.redirectsText).get("/ar/old/").to, "/ar/new/");
  assert.equal(parseDynamicRedirects(mod.redirectsText).length, 1);
  assert.deepEqual(headersFor(parseHeaders(mod.headersText), "/"), { Link: '</x>; rel="y"' });
  assert.match(readFileSync(out, "utf8"), /^\/\/ Generated by/);
});

test("the real site/public files bundle and contain the API redirect", () => {
  const dir = mkdtempSync(join(tmpdir(), "bundle-rules-real-"));
  const { redirects, headers } = bundleRules(undefined, join(dir, "rules.generated.js"));
  const dynamic = parseDynamicRedirects(redirects);
  assert.ok(dynamic.some((r) => r.pattern.test("/api/v1/meta/index.json")), "the /api/* rule is present");
  assert.ok(headersFor(parseHeaders(headers), "/").Link, "the homepage Link header is present");
});
